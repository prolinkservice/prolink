-- 測試模式
--
-- 職人接上來的官方帳號通常已經有幾百個好友。他想先自己試試看，
-- 又不敢拿真實客人冒險——這是每一個人導入時都會遇到的同一件事，
-- 不是誰的特例。
--
-- 打開之後，系統發出的所有 LINE 訊息只送給「已綁定的操作者」，
-- 也就是職人自己（與他的助理）。真實客人加好友、打關鍵字、
-- 按舊卡片上的按鈕，一律不會收到任何回應。
--
-- 刻意不做成環境變數：那是全站的開關，而這件事是一家店一家店的。
-- 也刻意不靠「把 webhook 關掉」：關了就得把 LINE 後台原本的
-- 歡迎訊息開回去，一來一往四個開關，遲早會忘記一個。
-- ═══════════════════════════════════════════════════════════════

alter table public.tenant_settings
  add column if not exists test_mode boolean not null default false;

comment on column public.tenant_settings.test_mode is
  '測試模式：LINE 訊息只發給已綁定的操作者，真實客人一則都收不到。導入期用';
